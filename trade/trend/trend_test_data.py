#
# trade/trend/trend_test_data.py
#
# TREND判定テスト用の価格データを生成する。
#
# UP / DOWN / RANGE / UNDEFINED の各パターンを
# TrendBarBuilder → TrendAnalyzer に渡して、
# TREND判定が想定どおりになるか確認する。
#


class TrendTestData:

    @staticmethod
    def create(test):

        #
        # 上昇トレンドのテストデータ
        #
        # 小さな上下動を含みながら、
        # 全体として価格が段階的に上昇する。
        #
        if test == "UP":

            base_prices = [
                1000, 1002, 1001, 1004, 1006,
                1005, 1008, 1010, 1009, 1012,
                1014, 1013, 1016, 1018, 1017,
                1020, 1022, 1021, 1024, 1026,
                1025, 1028, 1030, 1029, 1032,
                1034, 1033, 1036, 1038, 1037,
                1040, 1042, 1041, 1044, 1046,
                1045, 1048, 1050, 1049, 1052,
                1054, 1053, 1056, 1058, 1057,
                1060, 1062, 1061, 1064, 1066,
                1065, 1068, 1070, 1069, 1072,
                1074, 1073, 1076, 1078, 1077,
            ]

            #
            # 同じ上昇パターンを100円ずつ上方へ移動させて
            # 長い上昇トレンドを作る。
            #
            return [
                price + offset
                for offset in range(0, 1600, 100)
                for price in base_prices
            ]


        #
        # 下降トレンドのテストデータ
        #
        # 小さな上下動を含みながら、
        # 全体として価格が段階的に下降する。
        #
        if test == "DOWN":

            base_prices = [
                1060, 1058, 1059, 1056, 1054,
                1055, 1052, 1050, 1051, 1048,
                1046, 1047, 1044, 1042, 1043,
                1040, 1038, 1039, 1036, 1034,
                1035, 1032, 1030, 1031, 1028,
                1026, 1027, 1024, 1022, 1023,
                1020, 1018, 1019, 1016, 1014,
                1015, 1012, 1010, 1011, 1008,
                1006, 1007, 1004, 1002, 1003,
                1000, 998, 999, 996, 994,
                995, 992, 990, 991, 988,
                986, 987, 984, 982, 983,
            ]

            #
            # 同じ下降パターンを100円ずつ下方へ移動させて
            # 長い下降トレンドを作る。
            #
            return [
                price + 2000 - offset
                for offset in range(0, 1600, 100)
                for price in base_prices
            ]


        #
        # レンジ相場のテストデータ
        #
        # 1000付近を小さく上下するだけで、
        # 全体として上昇・下降しない状態を作る。
        #
        if test == "RANGE":

            base_prices = [
                1000, 1001, 999, 1000, 1001,
                999, 1000, 1001, 999, 1000,
                1001, 999, 1000, 1001, 999,
                1000, 1001, 999, 1000, 1001,
                999, 1000, 1001, 999, 1000,
                1001, 999, 1000, 1001, 999,
                1000, 1001, 999, 1000, 1001,
                999, 1000, 1001, 999, 1000,
                1001, 999, 1000, 1001, 999,
                1000, 1001, 999, 1000, 1001,
                999, 1000, 1001, 999, 1000,
                1001, 999, 1000, 1001, 999,
                1000, 1001, 999, 1000, 1001,
                999, 1000, 1001, 999, 1000,
            ]

            #
            # 同じ価格パターンを繰り返して、
            # 一定範囲内で価格が推移する状態を作る。
            #
            return [
                price
                for offset in range(0, 1600, 100)
                for price in base_prices
            ]


        #
        # 判定が衝突するケースのテストデータ
        #
        # 価格変化は強い下落だが、
        # 直近の高安構造は上昇となるように作る。
        #
        # → PRICE CHANGE -30 と
        #    STRUCTURE +40 が衝突して UNDEFINED
        #
        if test == "UNDEFINED":

            #
            # 長期的には上昇している価格を作る。
            #
            bar_prices = [
                1000 + i * 70
                for i in range(60)
            ]

            #
            # ここから直近9本。
            #
            # 急落した後に反発することで、
            # 価格変化と高安構造の判定が
            # 異なる方向になるようにする。
            #
            bar_prices += [
                5000, 4800, 4500, 4200, 3900,
                3600, 3800, 4000, 4200,
            ]

            prices = []

            #
            # 1本のTREND BARを15秒分の同一価格で構成する。
            #
            # TrendBarBuilderの設定に合わせて、
            # 1本 = 15秒としている。
            #
            for price in bar_prices:
                prices.extend([price] * 15)

            #
            # 最後の足を確定させるため、
            # 次の時刻の価格を1秒分追加する。
            #
            prices.append(4200)

            return prices


        #
        # 未定義のテスト区分が指定された場合。
        #
        raise ValueError(
            f"Unknown trend test type: {test}"
        )